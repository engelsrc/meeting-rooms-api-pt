-- Reservations table (business + audit/soft-delete convention from RF 001)
-- Soft-delete columns present but unused in RF 003 (cancel uses status + cancelled_*)
CREATE TABLE reservations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id       BIGINT NOT NULL,
    responsible   VARCHAR(100) NOT NULL,
    start_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    status        VARCHAR(20) NOT NULL,
    cancelled_by  VARCHAR(100) NULL,
    cancelled_at  TIMESTAMP WITH TIME ZONE NULL,
    created_by    VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by    VARCHAR(100) NULL,
    updated_at    TIMESTAMP NULL,
    is_deleted    BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_by    VARCHAR(100) NULL,
    deleted_at    TIMESTAMP NULL,
    CONSTRAINT fk_reservations_room FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT ck_reservations_status CHECK (status IN ('ACTIVE', 'CANCELLED')),
    CONSTRAINT ck_reservations_interval CHECK (end_at > start_at)
);
